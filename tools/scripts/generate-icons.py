#!/usr/bin/env python3
"""Generate offline native adapters from assets/icons/*.svg.
Dev dependency: pip install svgpathtools==1.8.0 (no runtime SVG library needed).
"""
import json
import math
from pathlib import Path
from xml.sax.saxutils import escape
from svgpathtools import svg2paths

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'assets/icons'
all_paths = {}
for svg in sorted(ASSETS.glob('*.svg')):
    paths, _ = svg2paths(str(svg))
    contours = []
    android = []
    for path in paths:
        android.append(path.d())
        for contour in path.continuous_subpaths():
            points = [[round(contour.start.real, 4), round(contour.start.imag, 4)]]
            for segment in contour:
                # At most 0.35 viewBox units between samples (under 0.5pt at 32pt).
                count = max(1, math.ceil(segment.length() / .35))
                points.extend([[round(segment.point(i/count).real, 4), round(segment.point(i/count).imag, 4)] for i in range(1, count+1)])
            contours.append(points)
    all_paths[svg.stem] = contours
    vector = ('<?xml version="1.0" encoding="utf-8"?>\n'
              '<!-- Generated from assets/icons; Lucide ISC/MIT, see assets/icons/LICENSE. -->\n'
              '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n')
    for d in android:
        vector += f'  <path android:pathData="{escape(d)}" android:fillColor="@android:color/transparent" android:strokeColor="#FF000000" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
    vector += '</vector>\n'
    (ROOT / f'platforms/android/app/src/main/res/drawable/lucide_{svg.stem.replace("-", "_")}.xml').write_text(vector)
packed = json.dumps(all_paths, separators=(',', ':'))
(ASSETS / 'paths.json').write_text(packed + '\n')
(ROOT / 'platforms/macos/src/LucideData.h').write_text('// Generated by tools/scripts/generate-icons.py; see assets/icons/LICENSE.\nstatic const char RTLucideData[] = ' + json.dumps(packed) + ';\n')
print(f'Generated {len(all_paths)} icons for Windows, macOS and Android.')
